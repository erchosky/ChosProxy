// Engagement tools that turn a stored exchange into reviewable HTML:
// CSRF proofs of concept and FrameLab (clickjacking) pages. Output is text
// for the tester to read, copy and host on a test origin; nothing here is
// executed or served by ChosProxy.

/** Escapes text for an HTML attribute or text node. */
export function escapeHtml(s: string): string {
  return s
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");
}

const decode = (s: string) => {
  try {
    return decodeURIComponent(s.replace(/\+/g, " "));
  } catch {
    return s;
  }
};

/** `a=1&b=2` → pairs, decoded. */
export function formPairs(text: string): [string, string][] {
  if (text === "") return [];
  return text.split("&").map((pair) => {
    const eq = pair.indexOf("=");
    return eq === -1 ? [decode(pair), ""] : [decode(pair.slice(0, eq)), decode(pair.slice(eq + 1))];
  });
}

export interface CsrfInput {
  method: string;
  url: string;
  contentType: string | null;
  body: string;
}

export interface CsrfOptions {
  autoSubmit: boolean;
}

export interface CsrfPoc {
  html: string;
  /** How the request is reproduced. */
  encoding: "urlencoded" | "multipart" | "text/plain" | "query";
  /** Limits the tester should know about. */
  notes: string[];
}

function multipartFields(body: string, contentType: string): [string, string][] {
  const m = /boundary=(?:"([^"]+)"|([^;\s]+))/i.exec(contentType);
  const boundary = m?.[1] ?? m?.[2];
  if (!boundary) return [];
  const out: [string, string][] = [];
  for (const part of body.split(`--${boundary}`).slice(1)) {
    if (part.startsWith("--")) break;
    const sep = part.includes("\r\n\r\n") ? "\r\n\r\n" : "\n\n";
    const at = part.indexOf(sep);
    if (at === -1) continue;
    const name = /name="([^"]*)"/i.exec(part.slice(0, at))?.[1];
    if (name !== undefined) out.push([name, part.slice(at + sep.length).replace(/\r?\n$/, "")]);
  }
  return out;
}

/** A cross-site request forgery proof of concept for a request. */
export function csrfPoc(input: CsrfInput, options: CsrfOptions): CsrfPoc {
  const notes: string[] = [];
  const method = input.method.toUpperCase();
  const type = (input.contentType ?? "").split(";")[0]?.trim().toLowerCase() ?? "";
  let action = input.url;
  let formMethod = method === "GET" ? "GET" : "POST";
  let enctype: string | null = null;
  let fields: [string, string][] = [];
  let encoding: CsrfPoc["encoding"];

  if (method === "GET") {
    const u = new URL(input.url);
    fields = formPairs(u.search.slice(1));
    u.search = "";
    action = u.toString();
    encoding = "query";
  } else if (type === "multipart/form-data" && input.contentType) {
    enctype = "multipart/form-data";
    fields = multipartFields(input.body, input.contentType);
    encoding = "multipart";
    notes.push("File parts are sent as text fields with the same content.");
  } else if (type === "" || type === "application/x-www-form-urlencoded") {
    fields = formPairs(input.body);
    encoding = "urlencoded";
  } else {
    // JSON or other bodies: the text/plain technique. The browser sends
    // `name=value`; splitting the body at its last '=' (or appending one)
    // keeps it intact apart from that character.
    enctype = "text/plain";
    encoding = "text/plain";
    const at = input.body.lastIndexOf("=");
    fields =
      at > 0 ? [[input.body.slice(0, at), input.body.slice(at + 1)]] : [[`${input.body}`, ""]];
    notes.push(
      `The body is sent as text/plain instead of ${type}; servers that check the Content-Type will reject it.`,
    );
    if (at <= 0) notes.push("An '=' is appended to the end of the body.");
  }
  if (method !== "GET" && method !== "POST") {
    formMethod = "POST";
    notes.push(
      `HTML forms cannot send ${method}; the PoC sends POST. Cross-site ${method} needs a CORS preflight the target must allow.`,
    );
  }
  notes.push("Cookies are only sent cross-site when their SameSite attribute allows it.");

  const inputs = fields
    .map(
      ([name, value]) =>
        `      <input type="hidden" name="${escapeHtml(name)}" value="${escapeHtml(value)}" />`,
    )
    .join("\n");
  const html = [
    "<!doctype html>",
    "<html>",
    "  <!-- CSRF proof of concept generated by ChosProxy. Use only against systems you are authorized to test. -->",
    "  <body>",
    `    <form action="${escapeHtml(action)}" method="${formMethod}"${
      enctype ? ` enctype="${enctype}"` : ""
    }>`,
    inputs,
    '      <input type="submit" value="Submit request" />',
    "    </form>",
    options.autoSubmit ? "    <script>document.forms[0].submit();</script>" : "",
    "  </body>",
    "</html>",
    "",
  ]
    .filter((l) => l !== "")
    .join("\n");
  return { html: `${html}\n`, encoding, notes };
}

// ---------------------------------------------------------------- FrameLab

export interface FramingVerdict {
  /** The page can be framed by another origin. */
  frameable: boolean;
  /** One line per header that decides it. */
  reasons: string[];
}

/** Whether a response can be framed cross-origin, from its headers. */
export function framingVerdict(headers: [string, string][]): FramingVerdict {
  const reasons: string[] = [];
  let blocked = false;
  const csp = headers
    .filter(([n]) => n.toLowerCase() === "content-security-policy")
    .map(([, v]) => v);
  const ancestors = csp
    .flatMap((v) => v.split(";"))
    .map((d) => d.trim())
    .find((d) => d.toLowerCase().startsWith("frame-ancestors"));
  if (ancestors) {
    const sources = ancestors.split(/\s+/).slice(1);
    const open = sources.some((s) => s === "*" || s === "https:" || s === "http:");
    if (open) {
      reasons.push(`CSP ${ancestors}: any origin may frame the page.`);
    } else {
      blocked = true;
      reasons.push(`CSP ${ancestors}: only the listed origins may frame the page.`);
    }
  }
  const xfo = headers.find(([n]) => n.toLowerCase() === "x-frame-options")?.[1].trim();
  if (xfo) {
    const v = xfo.toUpperCase();
    if (v === "DENY" || v === "SAMEORIGIN") {
      if (!ancestors) blocked = true;
      reasons.push(
        ancestors
          ? `X-Frame-Options: ${xfo} (browsers follow frame-ancestors when both are set).`
          : `X-Frame-Options: ${xfo}.`,
      );
    } else {
      reasons.push(`X-Frame-Options: ${xfo} is not supported by current browsers.`);
    }
  }
  if (!ancestors && !xfo) reasons.push("Neither X-Frame-Options nor CSP frame-ancestors is set.");
  return { frameable: !blocked, reasons };
}

export interface FrameOptions {
  /** Opacity of the framed page (0 = invisible, 1 = fully visible). */
  opacity: number;
  /** Size of the frame. */
  width: number;
  height: number;
  /** Where the decoy button sits over the framed page. */
  left: number;
  top: number;
  /** Decoy text. */
  decoy: string;
}

export const DEFAULT_FRAME: FrameOptions = {
  opacity: 0.3,
  width: 1000,
  height: 700,
  left: 100,
  top: 200,
  decoy: "Click here",
};

/** A clickjacking proof of concept: the page framed under a decoy. */
export function framePoc(url: string, o: FrameOptions): string {
  const n = (v: number, min: number, max: number) => Math.min(max, Math.max(min, Math.round(v)));
  const opacity = Math.min(1, Math.max(0, o.opacity));
  return `<!doctype html>
<html>
  <!-- Clickjacking proof of concept generated by ChosProxy (FrameLab). Use only against systems you are authorized to test. -->
  <head>
    <style>
      body { margin: 0; font-family: sans-serif; }
      #target { position: absolute; top: 0; left: 0; width: ${n(o.width, 100, 4000)}px; height: ${n(o.height, 100, 4000)}px; opacity: ${opacity}; z-index: 2; border: 0; }
      #decoy { position: absolute; top: ${n(o.top, 0, 4000)}px; left: ${n(o.left, 0, 4000)}px; z-index: 1; padding: 12px 20px; font-size: 18px; }
    </style>
  </head>
  <body>
    <button id="decoy">${escapeHtml(o.decoy)}</button>
    <iframe id="target" src="${escapeHtml(url)}"></iframe>
  </body>
</html>
`;
}
